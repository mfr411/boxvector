#!/usr/bin/env bash
# Regenerate documentation that is derived from the code:
#   docs/configuration.md  - every YAML option (from struct tags in pkg/config)
#   docs/cli.md            - --help of each command
#   README.md              - block between <!-- cli:begin --> and <!-- cli:end -->
# Run with `go generate` or `make docs`. CI runs it on every push to dev and
# commits the result, so these files never go stale.
set -euo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
bin=$tmp/boxvector
go build -o "$bin" .

{
  echo "# Configuration reference"
  echo
  echo "_Generated by \`docs/generate.sh\` from the source code. Do not edit by hand._"
  echo
  "$bin" docs 2>/dev/null
} > docs/configuration.md

{
  echo "# CLI reference"
  echo
  echo "_Generated by \`docs/generate.sh\`. Do not edit by hand._"
  for c in "" generate web "web passwd" status optimizer match dump config version; do
    echo
    echo "## boxvector${c:+ $c}"
    echo
    echo '```'
    # shellcheck disable=SC2086
    "$bin" $c --help 2>/dev/null
    echo '```'
  done
} > docs/cli.md

"$bin" --help > "$tmp/usage" 2>/dev/null
awk -v f="$tmp/usage" '
  /<!-- cli:begin -->/ { print; print "```"; while ((getline l < f) > 0) print l; print "```"; skip=1; next }
  /<!-- cli:end -->/   { skip=0 }
  !skip
' README.md > "$tmp/README.md"
cp "$tmp/README.md" README.md

echo "docs regenerated"
